import sys
from pathlib import Path

from agreement import agreement, condition, number, read_rows, select_pairs, unknown_conditions
from confusion import NO_ANSWER, accuracy_by_distance, confusion, false_alarms, is_mosquito

REST = ("rest", "post_exercise")
PLOT_SUFFIX = "_bland_altman.png"

PULSE = [
    {"kind": "heart_rate", "title": "Heart rate", "device": "device_hr", "ref": "ref_hr",
     "unit": "bpm", "tolerance": 5,
     "limits": "The pod is not clinically validated and is not a medical device."},
    {"kind": "spo2", "title": "SpO2", "device": "device_spo2", "ref": "ref_spo2",
     "unit": "points", "tolerance": 2,
     "limits": "The pod is not clinically validated and is not a medical device. "
               "Healthy people nearly all read 95-100%, so low oxygen readings were never tested "
               "and no accuracy is claimed at low oxygen."},
]
TEMP = {"kind": "air_temp_c", "title": "Air temperature", "device": "device_temp_c", "ref": "ref_temp_c",
        "unit": "°C", "tolerance": 1}
HUMIDITY = {"device": "device_rh", "ref": "ref_rh", "unit": "% RH", "tolerance": None}

INTRO = """# Hardware validation

Generated by `python validation/report.py` from the CSV files in `validation/`. Edit the CSV files, not this page.

Each comparison pairs a pod reading with a reference reading taken at the same moment. Bias is the mean of device minus reference. SD is the sample standard deviation of those differences (n - 1). The 95% limits of agreement are bias +/- 1.96 x SD. Rows with a blank or non-numeric reading are left out and counted. Targets are the team's own, not a regulatory standard. A sensor without data rows has no figures below and is absent from `public/validation/results.json`, which holds an empty object when no sensor has data.
"""


def f2(x):
    text = f"{x:.2f}"
    return "0.00" if text == "-0.00" else text


def signed(x):
    return "+" + f2(x) if f2(x) != "0.00" and x > 0 else f2(x)


def pct(share):
    return f"{round(share * 100)}%"


def r2(x):
    return None if x is None else round(x, 2) + 0.0


def stats_table(stats, excluded, unit, tolerance, people=None):
    lines = ["| Measure | Value |", "|---|---|"]
    if people is not None:
        lines.append(f"| People | {people} |")
    lines.append(f"| Pairs | {stats['n']} |")
    lines.append(f"| Rows excluded (blank or non-numeric reading) | {excluded} |")
    lines.append(f"| Bias (device minus reference) | {signed(stats['bias'])} {unit} |")
    if stats["sd"] is None:
        lines.append("| SD of differences | needs at least 2 pairs |")
        lines.append("| 95% limits of agreement | needs at least 2 pairs |")
    else:
        lines.append(f"| SD of differences | {f2(stats['sd'])} {unit} |")
        lines.append(f"| 95% limits of agreement | {signed(stats['loa_low'])} to {signed(stats['loa_high'])} {unit} |")
    lines.append(f"| Mean absolute error | {f2(stats['mae'])} {unit} |")
    if tolerance is not None:
        inside = round(stats["within_tolerance"] * stats["n"])
        lines.append(f"| Within team target (+/- {tolerance:g} {unit}) | "
                     f"{pct(stats['within_tolerance'])} ({inside} of {stats['n']}) |")
    return "\n".join(lines)


def bland_altman(path, pairs, stats, title, unit, extra=()):
    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    fig, ax = plt.subplots(figsize=(6, 4), dpi=100)
    for points, style in ((pairs, {"color": "#1f5f8b", "label": "rest and post-exercise" if extra else "pairs"}),
                          (extra, {"facecolors": "none", "edgecolors": "#b5482d", "label": "motion (not in limits)"})):
        if points:
            ax.scatter([(d + r) / 2 for _, d, r in points], [d - r for _, d, r in points], s=20, **style)
    ax.axhline(stats["bias"], color="#333333", linewidth=1, label=f"bias {signed(stats['bias'])}")
    for y in (stats["loa_low"], stats["loa_high"]):
        ax.axhline(y, color="#777777", linewidth=1, linestyle="--")
    ax.set_title(f"{title}: device against reference")
    ax.set_xlabel(f"mean of device and reference ({unit})")
    ax.set_ylabel(f"device minus reference ({unit})")
    ax.legend(fontsize=8)
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)


def agreement_block(pairs, excluded, spec, people, plots, extra=()):
    if not pairs:
        return "No pairs with both readings.", None
    stats = agreement([d for _, d, _ in pairs], [r for _, _, r in pairs], spec["tolerance"])
    parts = [stats_table(stats, excluded, spec["unit"], spec["tolerance"], people)]
    if stats["sd"] is not None and "kind" in spec:
        name = spec["kind"] + PLOT_SUFFIX
        bland_altman(plots / name, pairs, stats, spec["title"], spec["unit"], extra)
        parts.append(f"![Bland-Altman plot for {spec['title']}](plots/{name})")
    return "\n\n".join(parts), stats


def entry(stats, people):
    if stats is None or stats["sd"] is None:
        return None
    out = {k: (v if k == "n" else r2(v)) for k, v in stats.items()}
    out["people"] = people
    return out


def pulse_claim(people, unnamed, n):
    against = "against a consumer fingertip oximeter"
    if not people:
        return f"bench-compared in {n} paired readings {against}"
    adults = f"{people} adult" + ("" if people == 1 else "s")
    return f"bench-compared on {'at least ' if unnamed else ''}{adults} {against}"


def pulse_section(rows, spec, plots):
    head = f"## {spec['title']}"
    if not rows:
        return f"{head}\n\nNot tested\n", None
    pairs, excluded = select_pairs(rows, spec["device"], spec["ref"], REST)
    motion, motion_excluded = select_pairs(rows, spec["device"], spec["ref"], ("motion",))
    people = len({row["person"] for row, _, _ in pairs if row.get("person")})
    unnamed = sum(not row.get("person") for row, _, _ in pairs)
    block, stats = agreement_block(pairs, excluded, spec, people, plots, motion)
    out = [head,
           "Device: the pod's finger slot. Reference: a consumer fingertip pulse oximeter on the other hand. "
           "Rest and post-exercise pairs are combined. Motion pairs are reported separately as the failure case.",
           block]
    if unnamed:
        out.append(f"The person was not recorded for {unnamed} of {len(pairs)} pairs.")
    unknown = unknown_conditions(rows)
    if unknown:
        count = sum(condition(row) in unknown for row in rows)
        seen = ", ".join(value or "blank" for value in sorted(unknown, key=lambda v: v or "blank"))
        out.append(f"Rows left out because the condition is not rest, post_exercise or motion: {count} "
                   f"(values seen: {seen}).")
    out.append("### Failure case: finger moving")
    motion_rows = [row for row in rows if condition(row) == "motion"]
    if not motion_rows:
        out.append("No motion rows recorded.")
    else:
        motion_spec = {k: v for k, v in spec.items() if k != "kind"}
        out.append(agreement_block(motion, motion_excluded, motion_spec, None, plots)[0])
        table = ["| Person | Reading | Device | Reference | Note |", "|---|---|---|---|---|"]
        for row in motion_rows:
            cells = [row.get("person", ""), row.get("reading", ""), row.get(spec["device"], "") or "blank",
                     row.get(spec["ref"], "") or "blank", row.get("note", "")]
            table.append("| " + " | ".join(cells) + " |")
        out.append("\n".join(table))
    if stats is not None:
        out.append(f'Allowed claim: "{pulse_claim(people, unnamed, len(pairs))}".')
    out.append(f"Limits: {spec['limits']}")
    return "\n\n".join(out) + "\n", entry(stats, people)


def weather_section(rows, plots):
    head = f"## {TEMP['title']}"
    if not rows:
        return f"{head}\n\nNot tested\n", None
    pairs, excluded = select_pairs(rows, TEMP["device"], TEMP["ref"])
    block, stats = agreement_block(pairs, excluded, TEMP, None, plots)
    rh_pairs, rh_excluded = select_pairs(rows, HUMIDITY["device"], HUMIDITY["ref"])
    out = [head,
           "Device: the pod's air sensor in full shade, 1.5 to 2 m above ground, averaged to hourly values. "
           "Reference: hourly observations from the nearest official weather station.",
           block, "### Relative humidity",
           agreement_block(rh_pairs, rh_excluded, HUMIDITY, None, plots)[0] + "\n\nThe team set no humidity target."]
    if stats is not None:
        out.append('Allowed claim: "compared with hourly observations from an official weather station '
                   f'over {len(pairs)} hours".')
    out.append("Limits: this is sensor against station. NASA POWER's newest days lag by about two days, "
               "so sensor against NASA POWER for the same days follows once those days are published.")
    return "\n\n".join(out) + "\n", entry(stats, None)


def label_list(labels):
    labels = list(labels)
    return labels[0] if len(labels) == 1 else ", ".join(labels[:-1]) + " and " + labels[-1]


def mosquito_section(rows):
    head = "## Mosquito listener"
    if not rows:
        return f"{head}\n\nNot tested\n", None
    true, predicted, distances, excluded = [], [], [], 0
    for row in rows:
        distance = number(row.get("distance_cm", ""))
        if not row.get("true_label") or distance is None:
            excluded += 1
            continue
        true.append(row["true_label"])
        predicted.append(row.get("predicted_label") or NO_ANSWER)
        distances.append(distance)
    if not true:
        return f"{head}\n\nNo usable trials. Rows excluded (blank label or distance): {excluded}.\n", None
    result = confusion(true, predicted)
    n = len(true)
    out = [head,
           f"Clips played: {n}. Rows excluded (blank label or distance): {excluded}. "
           "Clips were played from one speaker at a fixed volume.",
           "### Confusion table",
           "Rows are the true label, columns are what the pod printed."]
    table = ["| True label | " + " | ".join(result["labels"]) + " |",
             "|---|" + "---|" * len(result["labels"])]
    for label, counts in zip(result["labels"], result["matrix"]):
        if sum(counts):
            table.append(f"| {label} | " + " | ".join(str(c) for c in counts) + " |")
    out.append("\n".join(table))
    recall = ["| Class | Correct | Clips | Recall |", "|---|---|---|---|"]
    for label, share in result["recall"].items():
        clips = true.count(label)
        recall.append(f"| {label} | {round(share * clips)} | {clips} | {pct(share)} |")
    out += ["### Recall per class", "\n".join(recall),
            f"Overall accuracy: {pct(result['accuracy'])} ({sum(t == p for t, p in zip(true, predicted))} of {n})."]
    alarms, quiet = false_alarms(true, predicted)
    out.append("### False alarms on non-mosquito clips")
    if quiet:
        names = sorted({t for t in true if not is_mosquito(t)})
        out.append(f"{alarms} of {quiet} non-mosquito clips ({pct(alarms / quiet)}) were reported as a mosquito. "
                   f"Labels counted as non-mosquito: {label_list(names)}.")
    else:
        out.append("No clip in trials.csv has a non-mosquito label, so false alarms were not measured.")
    by_distance = ["| Distance | Correct | Clips | Accuracy |", "|---|---|---|---|"]
    for distance, correct, clips in accuracy_by_distance(true, predicted, distances):
        by_distance.append(f"| {distance:g} cm | {correct} | {clips} | {pct(correct / clips)} |")
    out += ["### Accuracy at each distance", "\n".join(by_distance)]
    spots = label_list(f"{d:g}" for d in sorted(set(distances)))
    out.append(f'Allowed claim: "recognises recorded wingbeats played from a speaker at {spots} cm, {n} clips".')
    out.append("Limits: this is not field accuracy. A speaker is not a live mosquito. "
               "trials.csv does not record whether these clips were held out from the model's training data, "
               "so that is not known from this file.")
    entry_ = {"labels": result["labels"], "matrix": result["matrix"],
              "recall": {k: r2(v) for k, v in result["recall"].items()},
              "accuracy": r2(result["accuracy"]), "n": n}
    return "\n\n".join(out) + "\n", entry_


def write_results(paths, results):
    for path in paths:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(json.dumps(results, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")


def build(root):
    root = Path(root)
    data = root / "validation"
    out = root / "validation" / "report"
    plots = out / "plots"
    for old in plots.glob("*" + PLOT_SUFFIX):
        old.unlink()

    pulse_rows = read_rows(data / "pulse" / "readings.csv")
    sections, results = [], {}
    for spec in PULSE:
        text, item = pulse_section(pulse_rows, spec, plots)
        sections.append((spec["kind"], text, item))
    sections.append((TEMP["kind"], *weather_section(read_rows(data / "weather" / "log.csv"), plots)))
    sections.append(("mosquito", *mosquito_section(read_rows(data / "mosquito" / "trials.csv"))))
    for kind, _, item in sections:
        if item is not None:
            results[kind] = item

    out.mkdir(parents=True, exist_ok=True)
    (out / "REPORT.md").write_text(INTRO + "".join("\n" + text for _, text, _ in sections), encoding="utf-8")
    write_results([root / "public" / "validation" / "results.json"], results)
    if plots.exists() and not any(plots.iterdir()):
        plots.rmdir()
    return results


if __name__ == "__main__":
    build(sys.argv[1] if len(sys.argv) > 1 else Path(__file__).resolve().parent.parent)
