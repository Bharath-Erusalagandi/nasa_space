"""Writes hardware/cad/README.md from the parameters and out/checks.json, so every figure comes from the model."""

PRINT_SETTINGS = {
    "shell": "0.2 mm layers, 4 walls, 5 top/bottom layers, 15% gyroid, no support, textured sheet for the face",
    "rear_plate": "0.2 mm layers, 3 walls, 15% gyroid, no support",
    "tray": "0.2 mm layers, 3 walls, 15% gyroid, no support",
    "finger_cradle": "0.16 mm layers, 4 walls (opaque), 25% gyroid, no support, matte black",
    "camera_bezel": "0.16 mm layers, 100% (it is thin), no support, matte black",
    "speaker_clamp": "0.2 mm layers, 3 walls, 25% gyroid, no support",
    "cable_clamp": "0.2 mm layers, 100%, no support",
    "sensor_capsule": "0.16 mm layers, 3 walls, 20% gyroid, no support, 5 mm brim (narrow footprint), white ASA",
    "capsule_clip": "0.2 mm layers, 4 walls, 30% gyroid, no support, 5 mm brim, white ASA",
}

MEASURE = [
    ("MAX30101 SEN-16474", "board thickness ({max_t}), hole pattern ({max_hole_pitch} square), IC offset from the "
     "board centre (0 assumed), which face carries the Qwiic sockets (bottom assumed)",
     "sets the floor, window and pin positions; cut the board's power LED jumper so it does not light the tunnel"),
    ("OV5647 camera", "lens centre {cam_lens_from_top} below the board top edge, barrel {cam_barrel_d} dia, holder "
     "depth {cam_depth} overall, hole pattern {cam_holes[0]} x {cam_holes[1]}",
     "sets the post positions and the lens-to-aperture distance"),
    ("Grove Vision AI V2 + XIAO", "hole positions (2.5 in from the corners assumed), stack height with both USB-C "
     "plugs in (16 assumed), USB-C and CSI connector positions",
     "sets the tray standoffs and the ribbon end; Seeed's kit case STEP is the fastest source"),
    ("Speaker 40 mm", "rim thickness ({spk_rim_t} assumed) and basket diameter just behind the rim",
     "sets the clamp lip height"),
    ("USB mic dongle", "outline {dongle[0]} x {dongle[1]} x {dongle[2]} and where its sound holes sit",
     "sets the pocket and the mic port row"),
    ("CH334F hub", "hole positions (2.5 in from the corners assumed) and the USB-C height", "sets standoffs and the cable"
     " exit height"),
    ("USB audio adapter", "real size against the {adapter[0]} x {adapter[1]} x {adapter[2]} envelope",
     "sets the tray guides"),
    ("UV LED", "total height 8.6 and flange {led_cb_d} dia", "sets the counterbore so the tip stands {led_proud} proud"),
    ("Printer fit", "bezel press fit ({bezel_fit} per side), cradle slip fit ({cradle_fit}), tray slide "
     "({slide_fit}), heat-set insert pilot ({insert_pilot})", "print the bezel and cradle first and adjust these"),
]


def _fmt(s, P):
    return s.format(**vars(P))


def write_readme(res, P, path):
    parts = res["parts"]
    printed = [(n, p) for n, p in parts.items() if p["kind"] == "printed"]
    bought = [n for n, p in parts.items() if p["kind"] == "bought"]
    env = res["envelope"]
    L = []
    L.append("# Pod K-01 enclosure (CAD)\n")
    L.append("Parametric build123d model of the pod enclosure. Everything here is generated by "
             "`pod_k01.py`; this file is written by `readme.py` from the parameters and `out/checks.json`.\n")
    L.append("## Run\n")
    L.append("From the project folder, with build123d and Blender's bpy installed in two separate Python environments:\n")
    L.append("```\ncd hardware/cad && python pod_k01.py --render-meshes\n"
             "cd hardware/cad && python render.py\n```\n")
    L.append("`pod_k01.py` builds every part, runs the checks, writes `out/checks.json` and exits with code 1 "
             "when a check fails. Then it writes the STEP files, the 3MF files and both PDFs. `--render-meshes` "
             "also writes STL meshes to `build/render/` for `render.py`, which writes the previews in "
             "`out/engineering_previews/`.\n")
    L.append("## Envelope\n")
    e = env["enclosure_mm"]
    c = env["with_stowed_capsule_mm"]
    L.append(f"- Enclosure: {e[0]} wide x {e[1]} deep x {e[2]} tall (shell, rear plate, feet, finger lip, LED tip, "
             f"cable clamp).")
    L.append(f"- With the air sensor capsule stowed on the back: {c[0]} x {c[1]} x {c[2]}.")
    L.append(f"- Shell alone: {P.W:.0f} x {P.D:.0f} deep x {P.H:.0f}.\n")
    L.append("## Printed parts\n")
    L.append("| Part | Material | Print orientation | Bed footprint x height (mm) | Time (h) | Filament (g / m) |"
             " Settings |")
    L.append("|---|---|---|---|---|---|---|")
    for n, p in printed:
        est = p["estimate"]
        b = p["print_bbox_mm"]
        L.append(f"| {n} | {est['material']} | {p['print_orientation']} | {b[0]} x {b[1]} x {b[2]} | "
                 f"{est['print_h']} | {est['filament_g']} / {est['filament_m']} | {PRINT_SETTINGS.get(n, '')} |")
    t = res["print_totals"]
    L.append(f"\nTotal: about {t['print_h']} h and {t['filament_g']} g. These are estimates from part volume and "
             f"surface area ({t['method']}), not slicer output. Slice each 3MF before trusting them.\n")
    L.append("Every part fits a 220 x 220 bed and needs no support. Overhang area steeper than 45 degrees, from "
             "the print-orientation mesh, is listed per part in `checks.json`; what remains is the debossed "
             "label floor, holes of 6 mm or less in vertical walls, the cable tie bridge on the tray and the four "
             "short sensor pins under the cradle floor.\n")
    L.append("## Bought parts modelled\n")
    L.append(", ".join(bought) + ".\n")
    L.append("Each is a simple solid with the right outline, height, holes and connector positions. Colours: "
             "SparkFun red, Adafruit dark blue, steel USB shells, black connectors. The Seeed board colours "
             "(Vision AI V2 green, XIAO blue, camera green) are assumptions.\n")
    L.append("## Fasteners\n")
    L.append("- 13 M3 heat-set inserts (4.0 pilot, 6.7 deep): 4 shell corners, 2 cradle bosses, 3 speaker bosses, "
             "2 cable clamp bosses on the rear plate, 2 in the capsule clip.")
    L.append("- 4 M3 x 10 countersunk: rear plate. 2 M3 x 10 countersunk: cradle. 3 M3 x 10 pan: speaker clamp. "
             "2 M3 x 10 countersunk: cable clamp. 2 M3 x 8 countersunk: capsule clip, from inside the rear plate.")
    L.append("- M2 x 5 self-tapping: 4 camera, 4 Vision AI, 4 hub. M2 x 4 self-tapping with washers: 4 MAX30101 "
             "(its holes are 3.3).\n")
    L.append("## Assembly order\n")
    steps = [
        "Press all heat-set inserts.",
        "Seat the speaker rim in the ring behind the grille; fit the speaker clamp with 3 screws.",
        "Push the camera bezel in from behind, over the four posts. Screw the camera board onto the posts.",
        "Cut the MAX30101 power LED jumper. Screw the board under the cradle floor onto the four pins, IC in the "
        "window. Fit a foam or TPU ring in the entry groove. Push the cradle into the finger port from behind and "
        "screw its ears to the two bosses.",
        "Slide the USB mic dongle into the pocket under the top wall, sound holes up, foam ring on top. Push the "
        "UV LED up into its counterbore.",
        "On the tray: hub, Vision AI V2 with the XIAO seated, audio adapter. Plug the pigtails and USB-C plugs, "
        "keep the 25 mm bend zones clear. Connect the camera ribbon and fold its slack into one loop.",
        "Slide the tray onto the side rails from the back.",
        "Feed the sensor lead through the floor grommet hole and the tray hole; knot it in the capsule cap.",
        "Plug the USB-C cable into the hub, tie it to the tray anchor, pass it out through the keyhole.",
        "Screw the capsule clip to the rear plate from inside, then fit the rear plate with 4 screws and the "
        "cable clamp over the keyhole with 2 screws.",
    ]
    for i, s in enumerate(steps, 1):
        L.append(f"{i}. {s}")
    L.append("")
    L.append("## Measure before printing\n")
    L.append("Sizes marked [E] in the parameter block are estimates. Measure these and edit the parameter block:\n")
    L.append("| Part | Measure | Why |")
    L.append("|---|---|---|")
    for a, b, cc in MEASURE:
        L.append(f"| {a} | {_fmt(b, P)} | {_fmt(cc, P)} |")
    L.append("")
    L.append("## Checks (from out/checks.json)\n")
    L.append(f"- Result: {'all checks pass' if res['passed'] else 'FAILED: ' + '; '.join(res['failures'])}.")
    L.append(f"- Parts: {res['part_count']['printed']} printed, {res['part_count']['bought_models']} bought-part "
             f"models.")
    L.append(f"- {res['pairs_checked']} part pairs with neighbouring bounding boxes checked for intersection volume "
             f"and distance. Bought parts keep at least {res['min_clearance_required']} from every part they are "
             f"not mounted on (smallest found: {res['min_clearance_found']}). Declared mounting contacts must touch, "
             f"and every part must connect to the shell through contacts.")
    w = res["wall_thickness_mm"]
    L.append(f"- Thinnest measured wall: {res['min_wall_mm']} ({', '.join(f'{k} {v}' for k, v in w.items())}).")
    L.append(f"- Camera ribbon path {res['cables']['ribbon_path_mm']} of {P.ribbon_len:.0f}; the rest is a slack "
             f"loop. Sensor lead path outside the capsule {res['cables']['sensor_lead_path_mm']}.\n")
    L.append("## Not verified\n")
    L.append("- Nothing has been printed. Fits, insert bosses and the bezel press fit are untested.")
    L.append("- Bought-part sizes marked [E] are estimates; see the table above.")
    L.append("- Light sealing of the finger tunnel, speaker sound, airflow through the slots and heat are not "
             "simulated.")
    L.append("- Print time and filament are volume estimates, not slicer results.\n")
    L.append("## Files\n")
    for f in res.get("files", []):
        L.append(f"- `{f['path']}` ({f['kb']} KB)")
    path.write_text("\n".join(L) + "\n")
